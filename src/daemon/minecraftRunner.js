import { spawn } from 'child_process';
import path from 'path';
import fs from 'fs';
import https from 'https';
import http from 'http';
import { logStreamer } from './logStreamer.js';

export class MinecraftRunner {
  static SUPPORTED_ENGINES = ['paper', 'fabric', 'neoforge', 'forge', 'purpur', 'vanilla'];
  static DEFAULT_VERSIONS = [
    '1.21.4', '1.21.3', '1.21.1', '1.20.6', '1.20.4', 
    '1.20.2', '1.20.1', '1.19.4', '1.19.2', '1.18.2', 
    '1.16.5', '1.12.2', '1.8.8'
  ];

  // Helper to download a remote file stream
  static downloadFile(url, destPath) {
    return new Promise((resolve, reject) => {
      const client = url.startsWith('https') ? https : http;
      const request = client.get(url, (response) => {
        // Follow redirects
        if (response.statusCode >= 300 && response.statusCode < 400 && response.headers.location) {
          return this.downloadFile(response.headers.location, destPath).then(resolve).catch(reject);
        }

        if (response.statusCode !== 200) {
          return reject(new Error(`Download failed with HTTP status ${response.statusCode}`));
        }

        const fileStream = fs.createWriteStream(destPath);
        response.pipe(fileStream);

        fileStream.on('finish', () => {
          fileStream.close();
          resolve();
        });

        fileStream.on('error', (err) => {
          fs.unlink(destPath, () => {});
          reject(err);
        });
      });

      request.on('error', (err) => {
        fs.unlink(destPath, () => {});
        reject(err);
      });

      request.setTimeout(60000, () => {
        request.destroy();
        reject(new Error('Download timed out'));
      });
    });
  }

  // Fetch JSON helper
  static fetchJson(url) {
    return new Promise((resolve, reject) => {
      https.get(url, (res) => {
        if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          return this.fetchJson(res.headers.location).then(resolve).catch(reject);
        }
        let data = '';
        res.on('data', chunk => data += chunk);
        res.on('end', () => {
          try {
            resolve(JSON.parse(data));
          } catch (e) {
            reject(new Error('Invalid JSON response'));
          }
        });
      }).on('error', reject);
    });
  }

  // Configure server.properties and eula.txt
  static configureServerFiles(app, appDir) {
    const port = app.port || 25565;

    // 1. eula.txt (Auto-accept)
    const eulaPath = path.join(appDir, 'eula.txt');
    fs.writeFileSync(eulaPath, '# Generated by Eclipse Panel\neula=true\n', 'utf8');

    // 2. server.properties
    const propsPath = path.join(appDir, 'server.properties');
    let props = {};
    if (fs.existsSync(propsPath)) {
      try {
        const content = fs.readFileSync(propsPath, 'utf8');
        content.split('\n').forEach(line => {
          const trimmed = line.trim();
          if (trimmed && !trimmed.startsWith('#')) {
            const idx = trimmed.indexOf('=');
            if (idx > -1) {
              props[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim();
            }
          }
        });
      } catch (e) {}
    }

    // Apply managed properties
    props['server-port'] = String(port);
    props['query.port'] = String(port);
    props['server-ip'] = '0.0.0.0';
    if (!props['motd']) {
      props['motd'] = `\\u00a7b\\u00a7l${app.name} \\u00a77\\u00b7 \\u00a7fPowered by \\u00a79Eclipse Panel`;
    }
    if (props['online-mode'] === undefined) props['online-mode'] = 'false';
    if (!props['max-players']) props['max-players'] = '20';
    if (!props['enable-query']) props['enable-query'] = 'true';

    const serialized = Object.entries(props).map(([k, v]) => `${k}=${v}`).join('\n') + '\n';
    fs.writeFileSync(propsPath, serialized, 'utf8');
  }

  // Resolve and download appropriate server JAR
  static async setupMinecraftServer(app, appDir) {
    const engine = (app.engine || 'paper').toLowerCase().trim();
    const version = app.game_version || '1.21.1';
    const jarPath = path.join(appDir, 'server.jar');

    this.configureServerFiles(app, appDir);

    if (fs.existsSync(jarPath) && fs.statSync(jarPath).size > 1000000) {
      logStreamer.append(app.id, 'system', `[Minecraft] Found existing server.jar for ${engine} ${version}.`);
      return;
    }

    logStreamer.append(app.id, 'system', `[Minecraft] Provisioning ${engine.toUpperCase()} ${version}...`);

    try {
      if (engine === 'paper') {
        logStreamer.append(app.id, 'system', `[Minecraft] Querying PaperMC API for version ${version}...`);
        const buildsData = await this.fetchJson(`https://api.papermc.io/v2/projects/paper/versions/${version}/builds`);
        if (!buildsData.builds || buildsData.builds.length === 0) {
          throw new Error(`No PaperMC builds available for version ${version}`);
        }
        const latestBuild = buildsData.builds[buildsData.builds.length - 1];
        const buildNum = latestBuild.build;
        const downloadFile = latestBuild.downloads.application.name;
        const downloadUrl = `https://api.papermc.io/v2/projects/paper/versions/${version}/builds/${buildNum}/downloads/${downloadFile}`;
        
        logStreamer.append(app.id, 'system', `[Minecraft] Downloading Paper build #${buildNum}...`);
        await this.downloadFile(downloadUrl, jarPath);
        logStreamer.append(app.id, 'system', `[Minecraft] ✅ Paper ${version} installed successfully.`);
      } else if (engine === 'purpur') {
        const downloadUrl = `https://api.purpurmc.org/v2/purpur/${version}/latest/download`;
        logStreamer.append(app.id, 'system', `[Minecraft] Downloading latest Purpur ${version}...`);
        await this.downloadFile(downloadUrl, jarPath);
        logStreamer.append(app.id, 'system', `[Minecraft] ✅ Purpur ${version} installed successfully.`);
      } else if (engine === 'fabric') {
        logStreamer.append(app.id, 'system', `[Minecraft] Resolving Fabric Loader for ${version}...`);
        // Use standard stable Fabric loader 0.16.10 and installer 1.0.1
        const downloadUrl = `https://meta.fabricmc.net/v2/versions/loader/${version}/0.16.10/1.0.1/server/jar`;
        await this.downloadFile(downloadUrl, jarPath);
        logStreamer.append(app.id, 'system', `[Minecraft] ✅ Fabric server jar installed.`);
      } else if (engine === 'vanilla') {
        logStreamer.append(app.id, 'system', `[Minecraft] Fetching Mojang version manifest...`);
        const manifest = await this.fetchJson('https://piston-meta.mojang.com/mc/game/version_manifest_v2.json');
        const verObj = manifest.versions.find(v => v.id === version);
        if (!verObj) throw new Error(`Vanilla version ${version} not found in Mojang manifest`);
        const verData = await this.fetchJson(verObj.url);
        const serverUrl = verData.downloads.server.url;
        await this.downloadFile(serverUrl, jarPath);
        logStreamer.append(app.id, 'system', `[Minecraft] ✅ Vanilla ${version} server jar installed.`);
      } else if (engine === 'neoforge' || engine === 'forge') {
        // Fallback or Paper fallback if installer needs manual step
        logStreamer.append(app.id, 'system', `[Minecraft] Preparing ${engine.toUpperCase()} environment for ${version}...`);
        // Download Paper as compatible high-performance base if custom installer not yet run
        const buildsData = await this.fetchJson(`https://api.papermc.io/v2/projects/paper/versions/${version}/builds`).catch(() => null);
        if (buildsData && buildsData.builds && buildsData.builds.length > 0) {
          const latestBuild = buildsData.builds[buildsData.builds.length - 1];
          const downloadUrl = `https://api.papermc.io/v2/projects/paper/versions/${version}/builds/${latestBuild.build}/downloads/${latestBuild.downloads.application.name}`;
          await this.downloadFile(downloadUrl, jarPath);
        }
      }
    } catch (err) {
      logStreamer.append(app.id, 'stderr', `[Minecraft Provisioning Warning] ${err.message}. You can also upload your own "server.jar" directly in the Files tab.`);
    }
  }

  // Detect appropriate Java binary for Minecraft version
  static getJavaBinary(gameVersion = '') {
    const isWin = process.platform === 'win32';
    if (isWin) return 'java';

    // Minecraft 1.20.5+ requires Java 21
    // Minecraft 1.18 - 1.20.4 requires Java 17
    // Minecraft <= 1.16.5 runs on Java 8 or 17
    const java21 = '/usr/lib/jvm/java-21-openjdk-amd64/bin/java';
    const java17 = '/usr/lib/jvm/java-17-openjdk-amd64/bin/java';

    if (fs.existsSync(java21)) {
      return java21;
    }
    if (fs.existsSync(java17)) {
      return java17;
    }
    return 'java';
  }

  // Spawn Minecraft Server process
  static async spawnProcess(app, appDir, customEnv = {}) {
    const jarPath = path.join(appDir, 'server.jar');
    
    // Ensure files are set up
    if (!fs.existsSync(jarPath)) {
      await this.setupMinecraftServer(app, appDir);
    } else {
      this.configureServerFiles(app, appDir);
    }

    const javaBin = this.getJavaBinary(app.game_version);
    const maxRam = app.memory_limit ? Math.max(512, parseInt(app.memory_limit, 10)) : 2048;
    const minRam = Math.min(256, Math.floor(maxRam / 2));

    const args = [
      `-Xms${minRam}M`,
      `-Xmx${maxRam}M`,
      '-XX:+UseG1GC',
      '-XX:+ParallelRefProcEnabled',
      '-XX:MaxGCPauseMillis=200',
      '-XX:+UnlockExperimentalVMOptions',
      '-XX:+DisableExplicitGC',
      '-XX:+AlwaysPreTouch',
      '-jar',
      'server.jar',
      'nogui'
    ];

    logStreamer.append(app.id, 'system', `[Minecraft] Starting: ${javaBin} ${args.join(' ')}`);

    const child = spawn(javaBin, args, {
      cwd: appDir,
      env: {
        ...process.env,
        ...customEnv,
        SERVER_PORT: String(app.port || 25565),
      },
      stdio: ['pipe', 'pipe', 'pipe']
    });

    return child;
  }
}
